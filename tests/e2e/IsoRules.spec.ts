import { expect, test } from '@playwright/test';
import { analyze, login, textFile, watchPage } from './Helpers';

test('空审批与占位保留待补，审核上下文和用途随报告保存', async ({ page }) => {
  const clean = watchPage(page);
  await login(page);
  await expect(page.getByTestId('prescreen-scope')).toHaveValue('documents');
  await page.getByTestId('upload-files').setInputFiles(textFile('文件控制程序.txt', '文件控制程序\n文件编号：QP-01\n版本：A/0\n批准：____\n生效日期：待确认\n职责：待补充\n文件审批、发放及修订流程待确认。'));
  await expect(page.getByTestId('file-detection-0')).toBeVisible();
  await page.getByTestId('document-purpose-0').selectOption('procedure');
  await page.getByTestId('prescreen-fact-sterile').selectOption('no');
  const result = await analyze(page);
  expect(result.prescreen.version).toBe('2.0.0');
  expect(result.prescreen.context.scope).toBe('documents');
  expect(Object.values(result.prescreen.context.purposes)).toContain('procedure');
  expect(result.findings.find((row: { rule_id: string }) => row.rule_id === 'DOC-003').assessment_status).toBe('pending_input');
  await expect(page.getByTestId('finding-DOC-003')).toContainText('信息待补');
  await expect(page.getByTestId('prescreen-summary')).toContainText('人工核实');
  await expect(page.getByTestId('prescreen-coverage')).toBeVisible();
  await page.getByTestId('prescreen-fact-sterile').selectOption('unknown');
  await expect(page.getByTestId('results')).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await clean();
});

test('体系范围要求组织说明，无菌不适用保留条款理由和依据', async ({ page }) => {
  const clean = watchPage(page);
  await login(page);
  await page.getByTestId('prescreen-scope').selectOption('system');
  await expect(page.getByTestId('prescreen-scope-description')).toHaveAttribute('required', '');
  await page.getByTestId('prescreen-scope-description').fill('仅生产非无菌医疗器械，设计与生产纳入体系。');
  await page.getByTestId('prescreen-fact-sterile').selectOption('no');
  await page.getByTestId('prescreen-decisions-toggle').click();
  await page.getByTestId('prescreen-decision-clause').fill('7.5.5');
  await page.getByTestId('prescreen-decision-reason').fill('本组织没有无菌医疗器械生产活动');
  await page.getByTestId('prescreen-decision-evidence').fill('已确认的产品清单及注册产品技术要求');
  await page.getByTestId('prescreen-add-decision').click();
  await expect(page.getByTestId('prescreen-decisions')).toContainText('7.5.5');
  await page.getByTestId('upload-files').setInputFiles(textFile('质量手册.txt'));
  await expect(page.getByTestId('file-detection-0')).toBeVisible();
  const result = await analyze(page);
  expect(result.prescreen.context.scope).toBe('system');
  expect(result.prescreen.context.decisions.find((row: {clause: string}) => row.clause === '7.5.5').reason).toContain('无菌');
  expect(result.prescreen.context.decisions.find((row: {clause: string}) => row.clause === '7.5.5').basis).toContain('产品清单');
  await expect(page.getByTestId('prescreen-summary')).toContainText('体系级');
  await clean();
});

test('设计计划展示固定条款依据和生成待补事项', async ({ page }) => {
  const clean = watchPage(page);
  await login(page);
  await page.getByTestId('templates-nav').click();
  await page.getByTestId('template-design-plan').click();
  const parameters = { company: '规则测试组织', project: '设计计划规则验证', product: '测试产品', model: 'DP-A', number: 'DP-01', version: 'A/0', requirements: '产品输入和评审记录尚待项目组确认' };
  for (const [key, value] of Object.entries(parameters)) await page.getByTestId(`parameter-${key}`).fill(value);
  const creating = page.waitForResponse(row => row.url().endsWith('/api/v1/document-drafts') && row.request().method() === 'POST');
  await page.getByTestId('generate-draft').click();
  const response = await creating;
  expect(response.status()).toBe(200);
  const draft = (await response.json()).data;
  expect(draft.snapshot.requirements_basis.version).toBe('2.0.0');
  expect(draft.snapshot.generation_review.pending_count).toBeGreaterThan(0);
  await page.getByTestId('generation-basis-toggle').click();
  await expect(page.getByTestId('generation-basis')).toContainText('7.3.2');
  await expect(page.getByTestId('generation-review')).toContainText('待补');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await clean();
});

test('套册范围和用途随检查保存，重新打开可再次检查并保留原确认快照', async ({ page }) => {
  const clean = watchPage(page);
  await login(page);
  await page.getByTestId('suites-nav').click();
  await page.getByTestId('suite-name').fill('预筛范围套册');
  await page.getByTestId('suite-version').fill('UI-2');
  await page.getByTestId('suite-create').click();
  await expect(page.getByTestId('suite-detail')).toBeVisible();
  const importing = page.waitForResponse(row => row.url().endsWith('/imports') && row.request().method() === 'POST');
  await page.getByTestId('suite-upload').setInputFiles(textFile('空白审批表.txt', '空白审批表\n文件编号：FR-02\n版本：A/0\n批准：____\n日期：待填写\n活动记录与核对结果：待填写。'));
  const imported = await importing;
  expect(imported.status()).toBe(200);
  const suite = (await imported.json()).data;
  await page.getByTestId(`suite-item-purpose-${suite.items[0].id}`).selectOption('form');
  await page.getByTestId('prescreen-scope').selectOption('system');
  await page.getByTestId('prescreen-scope-description').fill('本次核对非无菌产品的组织体系文件集');
  await page.getByTestId('prescreen-fact-sterile').selectOption('no');
  await page.getByTestId('prescreen-decisions-toggle').click();
  await page.getByTestId('prescreen-decision-clause').fill('7.5.5');
  await page.getByTestId('prescreen-decision-reason').fill('组织不生产无菌产品');
  await page.getByTestId('prescreen-decision-evidence').fill('本次核对的产品清单与技术要求');
  await page.getByTestId('prescreen-add-decision').click();
  const inspecting = page.waitForResponse(row => row.url().endsWith('/inspections'));
  await page.getByTestId('suite-inspect').click();
  const inspected = await inspecting;
  expect(inspected.status()).toBe(200);
  const first = (await inspected.json()).data.inspection;
  const report = first.prescreen;
  expect(report.context.purposes[suite.items[0].id]).toBe('form');
  expect(report.context.scope).toBe('system');
  await expect(page.getByTestId('suite-inspection')).toContainText('信息待补');
  await page.getByTestId('suite-back').click();
  await page.getByTestId('suites-nav').click();
  await page.getByTestId(`suite-open-${suite.suite_uid}`).click();
  await expect(page.getByTestId('prescreen-scope')).toHaveValue('system');
  await page.getByTestId('prescreen-scope-description').fill('仅复核本套产品范围与文件控制');
  const rechecking = page.waitForResponse(row => row.url().endsWith('/inspections'));
  await page.getByTestId('suite-inspect').click();
  expect((await rechecking).status()).toBe(200);
  const stored = await page.request.get(`${process.env.E2E_API_BASE_URL}/api/v1/manual-suites/${suite.suite_uid}`);
  expect(stored.status()).toBe(200);
  expect((await stored.json()).data.inspection.prescreen.context.decisions[0].reason).toBe('组织不生产无菌产品');
  const historical = page.waitForResponse(row => row.url().endsWith(`/inspections/${first.checked_revision}`));
  await page.getByTestId(`suite-inspection-${first.checked_revision}`).click();
  const oldReport = await historical;
  expect(oldReport.status()).toBe(200);
  expect((await oldReport.json()).data.prescreen.context).toEqual(report.context);
  await expect(page.getByTestId('suite-historical-report')).toBeVisible();
  await expect(page.getByTestId('suite-inspection')).toContainText('本次核对非无菌产品的组织体系文件集');
  await page.getByTestId('suite-close-historical').click();
  await expect(page.getByTestId('suite-inspection')).toContainText('仅复核本套产品范围与文件控制');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await clean();
});
